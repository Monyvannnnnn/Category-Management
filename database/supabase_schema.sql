-- ------------------------------------------------------------
-- TABLE: telegram_subscribers
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS telegram_subscribers (
    chat_id VARCHAR(100) PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ------------------------------------------------------------
-- TABLE: grid_state
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS grid_state (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grid_name VARCHAR(100) NOT NULL UNIQUE,
    state_json TEXT DEFAULT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

DROP TRIGGER IF EXISTS trg_grid_state_updated_at ON grid_state;
CREATE TRIGGER trg_grid_state_updated_at
BEFORE UPDATE ON grid_state
FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();

-- ------------------------------------------------------------
-- TABLE: processed_telegram_updates
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS processed_telegram_updates (
    update_id BIGINT PRIMARY KEY,
    processed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ------------------------------------------------------------
-- TABLE: telegram_push_logs
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS telegram_push_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    chat_id VARCHAR(100) NOT NULL,
    message TEXT NOT NULL,
    status VARCHAR(50) NOT NULL,
    error_message TEXT DEFAULT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
